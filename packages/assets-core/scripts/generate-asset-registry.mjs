#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const PACKAGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CSV_PATH = path.join(PACKAGE_DIR, "assets.csv");
const DEFAULT_ASSETS_DIR = path.resolve(PACKAGE_DIR, "../../assets");
const OUTPUT_PATH = path.join(PACKAGE_DIR, "src/generated/assetRegistry.ts");

function parseCsvLine(line) {
  const values = [];
  let current = "";
  let quoted = false;

  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    if (quoted) {
      if (char === '"' && line[index + 1] === '"') {
        current += '"';
        index += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        current += char;
      }
    } else if (char === ",") {
      values.push(current);
      current = "";
    } else if (char === '"') {
      quoted = true;
    } else {
      current += char;
    }
  }

  values.push(current);
  return values;
}

function normalizeAssetPath(input) {
  const value = String(input || "").trim().replaceAll("\\", "/").replace(/^\/+/, "");
  if (!value) {
    throw new Error("Asset path must not be empty");
  }
  if (/^[a-z][a-z0-9+.-]*:/i.test(value) || value.startsWith("//")) {
    throw new Error(`Asset path must be relative: ${input}`);
  }

  const segments = value.split("/");
  if (segments.some(segment => !segment || segment === "." || segment === "..")) {
    throw new Error(`Asset path contains an unsafe segment: ${input}`);
  }

  return segments.join("/");
}

function assertAssetKey(key) {
  if (!/^[a-z][a-z0-9]*(?:[.-][a-z0-9]+)*$/i.test(key)) {
    throw new Error(`Invalid asset key: ${key}`);
  }
}

function readAssetsCsv(content) {
  const lines = content.split(/\r?\n/).filter(line => line.trim());
  if (lines.length === 0) {
    return [];
  }

  const header = parseCsvLine(lines[0]).map(value => value.trim());
  const keyIndex = header.indexOf("key");
  const pathIndex = header.indexOf("path");
  const descriptionIndex = header.indexOf("description");

  if (keyIndex < 0 || pathIndex < 0) {
    throw new Error("assets.csv must include key and path columns");
  }

  const entries = [];
  const seenKeys = new Set();
  for (const line of lines.slice(1)) {
    const row = parseCsvLine(line);
    const key = String(row[keyIndex] || "").trim();
    const assetPath = normalizeAssetPath(row[pathIndex] || "");
    const description = descriptionIndex >= 0 ? String(row[descriptionIndex] || "").trim() : "";

    assertAssetKey(key);
    if (seenKeys.has(key)) {
      throw new Error(`Duplicate asset key: ${key}`);
    }
    seenKeys.add(key);

    entries.push({
      key,
      path: assetPath,
      description,
      source: "csv",
    });
  }

  return entries;
}

async function pathExists(targetPath) {
  try {
    await fs.promises.access(targetPath);
    return true;
  } catch {
    return false;
  }
}

async function scanAssetDirectory(rootDir) {
  if (!(await pathExists(rootDir))) {
    return [];
  }

  const entries = [];
  async function walk(currentDir) {
    const dirents = await fs.promises.readdir(currentDir, {withFileTypes: true});
    dirents.sort((left, right) => left.name.localeCompare(right.name));

    for (const dirent of dirents) {
      const absolutePath = path.join(currentDir, dirent.name);
      if (dirent.isDirectory()) {
        await walk(absolutePath);
      } else if (dirent.isFile()) {
        const relativePath = normalizeAssetPath(path.relative(rootDir, absolutePath));
        entries.push({
          key: relativePath,
          path: relativePath,
          description: "",
          source: "scan",
        });
      }
    }
  }

  await walk(rootDir);
  return entries;
}

function mergeEntries(manualEntries, scannedEntries) {
  const entriesByKey = new Map();

  for (const entry of [...scannedEntries, ...manualEntries]) {
    const existing = entriesByKey.get(entry.key);
    if (existing && existing.path !== entry.path) {
      throw new Error(`Duplicate asset key with different paths: ${entry.key} (${existing.path} vs ${entry.path})`);
    }
    entriesByKey.set(entry.key, entry);
  }

  return Array.from(entriesByKey.values()).sort((left, right) => left.key.localeCompare(right.key));
}

function renderRegistry(entries) {
  const rows = entries.map(entry => {
    const descriptionLine = entry.description ? `,\n    description: ${JSON.stringify(entry.description)}` : "";
    return `  ${JSON.stringify(entry.key)}: {\n    path: ${JSON.stringify(entry.path)},\n    source: ${JSON.stringify(entry.source)}${descriptionLine},\n  }`;
  });

  return `// This file is generated by scripts/generate-asset-registry.mjs. Do not edit by hand.\n\nexport const assetRegistry = {\n${rows.join(",\n")}\n} as const;\n\nexport type AssetKey = keyof typeof assetRegistry;\n`;
}

const manualEntries = readAssetsCsv(await fs.promises.readFile(CSV_PATH, "utf8"));
const scannedEntries = await scanAssetDirectory(process.env.CHANGEBATTLE_ASSETS_DIR || DEFAULT_ASSETS_DIR);
const entries = mergeEntries(manualEntries, scannedEntries);
await fs.promises.mkdir(path.dirname(OUTPUT_PATH), {recursive: true});
await fs.promises.writeFile(OUTPUT_PATH, renderRegistry(entries));
console.info(
  `Generated ${path.relative(PACKAGE_DIR, OUTPUT_PATH)} from ${entries.length} asset(s) ` +
    `(${manualEntries.length} manual, ${scannedEntries.length} scanned)`,
);
